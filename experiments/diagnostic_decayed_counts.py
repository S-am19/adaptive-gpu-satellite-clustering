"""Paired validation diagnostic for cumulative versus decayed Mini-Batch counts.

This is a separately labeled research diagnostic. It does not replace or call
fit_minibatch_cpu. Both update rules receive the same pre-generated sample
indices, exact CPU assignments, and full-data SSE checkpoints.
"""
import argparse
import csv
from datetime import datetime, timezone
import hashlib
import json
import platform
import shutil
import sys
from pathlib import Path
from time import perf_counter

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from pcap.assignments_exact import ExactCPUBackend, accumulate_cluster_stats
from pcap.initialization import initialize_centroids


def sha256_array(array):
    array = np.ascontiguousarray(array)
    return hashlib.sha256(memoryview(array).cast("B")).hexdigest()


def movement(current, previous):
    delta = current.astype(np.float64) - previous.astype(np.float64)
    return float(np.sqrt(np.max(np.sum(delta * delta, axis=1))))


def full_sse(backend, points, centroids):
    assigned = backend.assign(points, centroids)
    return float(np.sum(assigned.squared_distances, dtype=np.float64))


def parser():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--scene-dir", type=Path, required=True,
                   help="Prepared validation scene directory containing X.npy")
    p.add_argument("--output-dir", type=Path, required=True,
                   help="New output directory; existing directories are rejected")
    p.add_argument("--k", type=int, default=16)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--updates", type=int, default=5000)
    p.add_argument("--batch-size", type=int, default=8192)
    p.add_argument("--checkpoint-interval", type=int, default=100)
    p.add_argument("--forgetting-half-life-passes", type=float, default=10.0)
    p.add_argument("--target-sse", type=float, default=25614.78637147278)
    p.add_argument("--reference-jsonl", type=Path,
                   help="Optional archived cumulative run used to validate replay checkpoints")
    return p


def main(argv=None):
    args = parser().parse_args(argv)
    if min(args.k, args.updates, args.batch_size, args.checkpoint_interval) < 1:
        raise SystemExit("K, updates, batch size and checkpoint interval must be positive")
    if not np.isfinite(args.forgetting_half_life_passes) or args.forgetting_half_life_passes <= 0:
        raise SystemExit("forgetting half-life must be positive and finite")
    if not np.isfinite(args.target_sse) or args.target_sse < 0:
        raise SystemExit("target SSE must be finite and nonnegative")

    scene_dir = args.scene_dir if args.scene_dir.is_absolute() else ROOT / args.scene_dir
    output_dir = args.output_dir if args.output_dir.is_absolute() else ROOT / args.output_dir
    output_dir.mkdir(parents=True, exist_ok=False)
    points = np.load(scene_dir / "X.npy", allow_pickle=False)
    if points.dtype != np.float32 or points.ndim != 2 or not np.isfinite(points).all():
        raise ValueError("X.npy must be a finite float32 [N,D] matrix")
    n, d = points.shape
    if args.k > n or args.batch_size > n:
        raise ValueError("K and batch size must not exceed N")
    centroids0 = initialize_centroids(points, args.k, seed=args.seed)
    x_hash, c0_hash = sha256_array(points), sha256_array(centroids0)

    # Save the exact stream generated by the production sampler policy.
    indices_path = output_dir / "batch_indices.npy"
    indices = np.lib.format.open_memmap(
        indices_path, mode="w+", dtype=np.int32,
        shape=(args.updates, args.batch_size))
    rng = np.random.default_rng(args.seed)
    for step in range(args.updates):
        indices[step] = rng.choice(n, size=args.batch_size, replace=False)
    indices.flush()
    del indices
    indices = np.load(indices_path, mmap_mode="r", allow_pickle=False)

    backend = ExactCPUBackend()
    warm = np.ascontiguousarray(points[:min(n, args.batch_size)])
    warm_assignment = backend.assign(warm, centroids0)
    accumulate_cluster_stats(warm, warm_assignment.labels, args.k)
    backend.assign(points[:1], centroids0)

    archived_q = None
    reference_path = None
    if args.reference_jsonl:
        reference_path = args.reference_jsonl if args.reference_jsonl.is_absolute() else ROOT / args.reference_jsonl
        for line in reference_path.open():
            record = json.loads(line)
            if (record.get("phase") == "measured" and record.get("repeat") == 0
                    and record.get("method") == "C1"):
                if record.get("X_sha256") != x_hash or record.get("C0_sha256") != c0_hash:
                    raise ValueError("archived reference X/C0 hashes do not match this run")
                archived_q = {int(row["step"]): float(row["full_data_sse"])
                              for row in record["metadata"]["quality_history"]}
                break
        if archived_q is None:
            raise ValueError("matching C1 replay record was not found")

    half_life_observations = args.forgetting_half_life_passes * n
    forgetting = 0.5 ** (args.batch_size / half_life_observations)
    checkpoints = set(range(args.checkpoint_interval, args.updates + 1,
                            args.checkpoint_interval)) | {args.updates}
    rows = []
    summaries = {}
    for variant in ("cumulative_count", "decayed_count"):
        centroids = centroids0.copy()
        sums = np.zeros((args.k, d), dtype=np.float64)
        counts = np.zeros(args.k, dtype=np.int64 if variant == "cumulative_count" else np.float64)
        checkpoint_centroids = centroids.copy()
        sse0 = full_sse(backend, points, centroids)
        rows.append(_checkpoint_row(variant, 0, 0, sse0, 0.0, 0.0, counts,
                                    0.0, 0.0, 1.0 if variant == "cumulative_count" else forgetting,
                                    args.target_sse, args.k))
        update_time = checkpoint_time = 0.0
        last_movement = 0.0
        fit_start = perf_counter()
        for step in range(1, args.updates + 1):
            batch = np.ascontiguousarray(points[indices[step - 1]])
            started = perf_counter()
            assigned = backend.assign(batch, centroids)
            stats = accumulate_cluster_stats(batch, assigned.labels, args.k)
            previous = centroids.copy()
            if variant == "cumulative_count":
                sums += stats.sums
                counts += stats.counts
            else:
                sums *= forgetting
                counts *= forgetting
                sums += stats.sums
                counts += stats.counts
            active = counts > 0
            centroids[active] = (sums[active] / counts[active, None]).astype(np.float32)
            if not np.isfinite(sums).all() or not np.isfinite(centroids).all():
                raise FloatingPointError(f"nonfinite {variant} state at update {step}")
            last_movement = movement(centroids, previous)
            update_time += perf_counter() - started
            if step in checkpoints:
                started = perf_counter()
                sse = full_sse(backend, points, centroids)
                elapsed_eval = perf_counter() - started
                checkpoint_time += elapsed_eval
                elapsed = perf_counter() - fit_start
                rows.append(_checkpoint_row(
                    variant, step, step * args.batch_size, sse,
                    movement(centroids, checkpoint_centroids), last_movement,
                    counts, elapsed_eval, elapsed,
                    1.0 if variant == "cumulative_count" else forgetting,
                    args.target_sse, args.k))
                checkpoint_centroids = centroids.copy()
        elapsed = perf_counter() - fit_start
        summaries[variant] = dict(
            final_sse=rows[-1]["full_sse"],
            target_satisfied=rows[-1]["full_sse"] <= args.target_sse,
            points_processed=args.updates * args.batch_size,
            final_centroid_movement=last_movement,
            effective_counts=[float(value) for value in counts],
            run_wall_s=elapsed, update_time_s=update_time,
            full_data_checkpoint_time_s=checkpoint_time,
            centroids_sha256=sha256_array(centroids))

    cumulative_rows = {int(row["step"]): row for row in rows
                       if row["variant"] == "cumulative_count"}
    mismatches = []
    if archived_q:
        for step, expected in archived_q.items():
            if step in cumulative_rows and not np.isclose(
                    cumulative_rows[step]["full_sse"], expected, rtol=0.0, atol=1e-8):
                mismatches.append((step, cumulative_rows[step]["full_sse"], expected))
        if mismatches:
            raise RuntimeError(f"cumulative replay differs from archived checkpoints: {mismatches[:5]}")

    csv_path = output_dir / "checkpoint_metrics.csv"
    with csv_path.open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    manifest = dict(
        diagnostic="separately labeled experimental decayed-count update; production baseline unchanged",
        dataset=str(scene_dir), shape=[n, d], k=args.k, seed=args.seed,
        batch_size=args.batch_size, updates=args.updates,
        checkpoint_interval=args.checkpoint_interval,
        sampling_policy="same pre-generated NumPy default_rng(seed).choice(N,batch_size,replace=False) sequence for both variants",
        x_sha256=x_hash, c0_sha256=c0_hash,
        batch_indices_file=indices_path.name,
        batch_indices_sha256=sha256_array(np.asarray(indices)),
        cumulative_rule="S <- S + batch_sums; count <- count + batch_counts; centroid <- S/count",
        decayed_rule="S <- lambda*S + batch_sums; effective_count <- lambda*effective_count + batch_counts; centroid <- S/effective_count",
        forgetting_factor_per_batch=forgetting,
        forgetting_half_life_passes=args.forgetting_half_life_passes,
        forgetting_half_life_observations=half_life_observations,
        frozen_target_sse=args.target_sse,
        reference_jsonl=str(reference_path) if reference_path else None,
        cumulative_replay_matches_archived_checkpoints=not mismatches,
        variants=summaries,
        timing_scope="Numba warmed; each method includes batch gather, exact batch assignment, accumulation/update and exact full-data SSE checkpoints; one diagnostic run, not a performance benchmark",
        execution_order=["cumulative_count", "decayed_count"],
        environment=dict(python=sys.version, numpy=np.__version__, platform=platform.platform()),
        created_utc=datetime.now(timezone.utc).isoformat(),
        git_head=__import__("subprocess").check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
        source_hashes={p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest()
                       for p in ["src/pcap/minibatch.py", "src/pcap/assignments_exact.py", "src/pcap/initialization.py"]})
    (output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2, allow_nan=False) + "\n")
    shutil.copy2(Path(__file__), output_dir / Path(__file__).name)
    _write_checksums(output_dir)
    print(json.dumps(summaries, indent=2))
    print(f"forgetting factor per batch: {forgetting:.12g}")
    print(f"artifacts: {output_dir}")


def _checkpoint_row(variant, step, processed, sse, checkpoint_move, last_move,
                    counts, eval_time, elapsed, forgetting, target, k):
    row = dict(variant=variant, step=step, points_processed=processed,
               full_sse=sse, relative_to_frozen_target=sse / target - 1.0,
               checkpoint_centroid_movement=checkpoint_move,
               last_update_movement=last_move,
               cumulative_points=processed,
               effective_count_sum=float(np.sum(counts)),
               effective_count_min=float(np.min(counts)),
               effective_count_max=float(np.max(counts)),
               forgetting_factor=forgetting,
               checkpoint_eval_s=eval_time, run_wall_s=elapsed)
    row.update({f"count_{j}": float(counts[j]) for j in range(k)})
    return row


def _write_checksums(directory):
    checksum_path = directory / "checksums.sha256"
    with checksum_path.open("w") as stream:
        for path in sorted(directory.iterdir()):
            if path.is_file() and path != checksum_path:
                digest = hashlib.sha256(path.read_bytes()).hexdigest()
                stream.write(f"{digest}  {path.name}\n")


if __name__ == "__main__":
    main()
